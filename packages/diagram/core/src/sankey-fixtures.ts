import { parseSankeyDiagram, type SankeyDiagram } from "./types/sankey.js";

const flow = (source: string, target: string, value: number, label?: string) => ({
	source,
	target,
	value,
	...(label === undefined ? {} : { label }),
});

const named = (...labels: string[]) =>
	labels.map((label) => ({
		id: label
			.toLowerCase()
			.replace(/[^\p{L}\p{N}]+/gu, "-")
			.replace(/^-+|-+$/gu, ""),
		label,
	}));

