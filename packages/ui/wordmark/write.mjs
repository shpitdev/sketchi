/**
 * Re-inks the wordmark: `node packages/ui/wordmark/write.mjs` rewrites
 * src/components/sketchi-wordmark-ink.ts from strokes.mjs. With `--check` it
 * only reports whether that file is current.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { inkWordmark } from "./ink.mjs";
import { strokes } from "./strokes.mjs";

export const OUTPUT = fileURLToPath(
	new URL("../src/components/sketchi-wordmark-ink.ts", import.meta.url),
);

export function render() {
	const { width, height, d } = inkWordmark(strokes);
	return `// Generated by packages/ui/wordmark/write.mjs from strokes.mjs. Do not edit by hand.

/** The hand-written Sketchi wordmark: one filled path in a ${width} by ${height} box. */
export const WORDMARK_WIDTH = ${width}

export const WORDMARK_HEIGHT = ${height}

export const WORDMARK_PATH =
  "${d}"
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const next = render();
	if (process.argv.includes("--check")) {
		if (readFileSync(OUTPUT, "utf8") !== next) {
			console.error("sketchi-wordmark-ink.ts is stale: run `pnpm nx run ui:wordmark`.");
			process.exit(1);
		}
	} else {
		writeFileSync(OUTPUT, next);
		console.log(`Wrote ${OUTPUT} (${Buffer.byteLength(next)} bytes)`);
	}
}
